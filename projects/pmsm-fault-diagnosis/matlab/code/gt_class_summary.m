function T=gt_class_summary(M,classes)
rows=cell(numel(classes),1);
for j=1:numel(classes)
    a=M(M.Label==classes(j),:); f=a(a.IsFault,:);
    delay=f.FirstCorrect_ms(isfinite(f.FirstCorrect_ms));
    med=NaN; worst=NaN;
    if ~isempty(delay), med=median(delay); worst=max(delay); end
    rows{j}=struct('Label',classes(j),'TestRecords',height(a),'FaultRecords',height(f), ...
        'MissedRecords',sum(f.Missed),'CorrectByOneCycle',sum(f.CorrectByOneCycle), ...
        'StableCorrectByOneCycle',sum(f.StableCorrectByOneCycle), ...
        'MedianCorrectDelay_ms',med,'WorstObservedCorrectDelay_ms',worst, ...
        'MeanPostFaultCorrectTimeFraction',mean(f.PostFaultCorrectTimeFraction,'omitnan'), ...
        'WrongAfterFirstCorrectRecords',sum(f.WrongAfterFirstCorrect), ...
        'NormalFalseAlarmEvents',sum(a.NormalFalseAlarmEvents), ...
        'NormalExposure_s',sum(a.NormalObservation_s));
end
T=struct2table(vertcat(rows{:}));
end
